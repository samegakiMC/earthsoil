/* =========================
   SHOW TOPIC
========================= */

function showTopic(topicName) {

    const contentBox =
        document.getElementById(
            "contentBox"
        );

    if (!contentBox) return;

    const topic =
        topics[topicName];

    if (!topic) {

        contentBox.innerHTML = `
            <div class="article-main-title">
                <div>
                    <h1>ไม่พบข้อมูล</h1>
                    <p>ลองเลือกหัวข้ออื่น</p>
                </div>
            </div>
        `;

        return;
    }


    let html = `

        <div class="article-main-title">

            <div class="article-icon">
                ${topic.icon}
            </div>

            <div>

                <p class="tag">
                    EARTHSOIL KNOWLEDGE
                </p>

                <h1>
                    ${topic.title}
                </h1>

                <p>
                    ${topic.subtitle || ""}
                </p>

            </div>

        </div>

    `;


    /* =========================
       QUIZ
    ========================= */

    if (topic.quiz) {

        html += `

            <div class="quiz-container">

                <div class="quiz-intro">

                    <p class="tag">
                        KNOWLEDGE TEST
                    </p>

                    <h2>
                        🧠 แบบทดสอบ 12 ข้อ
                    </h2>

                    <p>
                        เลือกคำตอบที่ถูกต้องที่สุด
                    </p>

                    <div class="quiz-progress">
                        <div
                            id="quizProgress"
                            class="quiz-progress-bar">
                        </div>
                    </div>

                </div>

        `;


        topic.questions.forEach(
            (q, index) => {

                html += `

                    <div class="question">

                        <h3>
                            ${index + 1}.
                            ${q.question}
                        </h3>

                        <div class="choices">

                `;


                q.choices.forEach(
                    (choice, choiceIndex) => {

                        html += `

                            <button
                                class="choice"
                                onclick="
                                    answerQuestion(
                                        ${index},
                                        ${choiceIndex},
                                        this
                                    )
                                "
                            >
                                ${choice}
                            </button>

                        `;

                    }
                );


                html += `

                        </div>

                        <div
                            id="result-${index}"
                            class="answer-result">
                        </div>

                    </div>

                `;

            }
        );


        html += `

                <div class="score-box">

                    <h2>
                        คะแนน
                        <span id="score">0</span>
                        /
                        ${topic.questions.length}
                    </h2>

                    <p id="scoreMessage">
                        เริ่มทำแบบทดสอบได้เลย!
                    </p>

                    <button
                        class="main-btn"
                        onclick="resetQuiz()"
                    >
                        🔄 ทำใหม่
                    </button>

                </div>

            </div>

        `;


        contentBox.innerHTML = html;

        window.currentQuiz = topic;

        score = 0;

        answered = [];

        return;
    }


    /* =========================
       NORMAL ARTICLE
    ========================= */

    topic.sections.forEach(
        (section, index) => {

            html += `

                <section class="article-section">

                    <div class="section-number">
                        ${String(index + 1)
                            .padStart(2, "0")}
                    </div>

                    <div>

                        <h2>
                            ${section.title}
                        </h2>

                        <p>
                            ${section.text}
                        </p>

                    </div>

                </section>

            `;

        }
    );


    contentBox.innerHTML = html;

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


/* =========================
   QUIZ SYSTEM
========================= */

let score = 0;

let answered = [];


function answerQuestion(
    questionIndex,
    selected,
    button
) {

    const quiz =
        window.currentQuiz;

    if (!quiz) return;

    if (answered[questionIndex])
        return;

    answered[questionIndex] = true;

    const question =
        quiz.questions[
            questionIndex
        ];

    const result =
        document.getElementById(
            `result-${questionIndex}`
        );

    const buttons =
        button.parentElement
            .querySelectorAll(
                ".choice"
            );


    buttons.forEach(
        btn => {

            btn.disabled = true;

        }
    );


    if (
        selected ===
        question.answer
    ) {

        score++;

        button.classList.add(
            "correct"
        );

        result.innerHTML = `

            <span class="correct-text">
                ✓ ถูกต้อง!
            </span>

        `;

    } else {

        button.classList.add(
            "wrong"
        );

        buttons[
            question.answer
        ].classList.add(
            "correct"
        );

        result.innerHTML = `

            <span class="wrong-text">
                ✕ ยังไม่ถูก
            </span>

        `;

    }


    const scoreElement =
        document.getElementById(
            "score"
        );

    if (scoreElement) {

        scoreElement.textContent =
            score;

    }


    /* QUIZ PROGRESS */

    const answeredCount =
        answered.filter(Boolean).length;

    const progress =
        (answeredCount /
            quiz.questions.length) *
        100;

    const progressBar =
        document.getElementById(
            "quizProgress"
        );

    if (progressBar) {

        progressBar.style.width =
            progress + "%";

    }


    /* FINAL MESSAGE */

    if (
        answeredCount ===
        quiz.questions.length
    ) {

        showFinalScore(
            score,
            quiz.questions.length
        );

    }

}


/* =========================
   FINAL SCORE
========================= */

function showFinalScore(
    score,
    total
) {

    const message =
        document.getElementById(
            "scoreMessage"
        );

    if (!message) return;

    const percent =
        Math.round(
            (score / total) * 100
        );


    if (percent >= 90) {

        message.innerHTML =
            "🏆 ยอดเยี่ยม! คุณเข้าใจเรื่องดินได้ดีมาก";

    }

    else if (percent >= 70) {

        message.innerHTML =
            "🌟 ดีมาก! ความรู้ของคุณอยู่ในระดับดี";

    }

    else if (percent >= 50) {

        message.innerHTML =
            "🌱 ใช้ได้! ลองอ่านบทความเพิ่มเติมอีกนิด";

    }

    else {

        message.innerHTML =
            "📚 ลองกลับไปอ่านบทความ แล้วทดสอบอีกครั้ง";

    }

}


/* =========================
   RESET
========================= */

function resetQuiz() {

    score = 0;

    answered = [];

    showTopic("quiz");

}
