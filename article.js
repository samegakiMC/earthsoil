/* =====================================================
   SHOW TOPIC
===================================================== */

function showTopic(topicName) {

    const contentBox =
        document.getElementById("contentBox");

    if (!contentBox) return;


    const topic =
        topics[topicName];


    if (!topic) {

        contentBox.innerHTML = `
            <div class="article-main-title">
                <div class="article-icon">❓</div>

                <div>
                    <p class="tag">
                        ERROR
                    </p>

                    <h1>
                        ไม่พบข้อมูล
                    </h1>

                    <p>
                        ลองเลือกหัวข้ออื่นจากเมนู
                    </p>
                </div>
            </div>
        `;

        return;
    }


    let html = `

        <div class="article-main-title">

            <div class="article-icon">
                ${topic.icon}
            </div>

            <div>

                <p class="tag">
                    DETAILED ARTICLE
                </p>

                <h1>
                    ${topic.title}
                </h1>

                <p>
                    ${topic.subtitle || ""}
                </p>

            </div>

        </div>

    `;


    /* =================================================
       QUIZ
    ================================================= */

    if (topic.quiz) {

        html += `

            <div class="quiz-container">

                <div class="quiz-intro">

                    <h2>
                        🧠 ทดสอบความเข้าใจ
                    </h2>

                    <p>
                        เลือกคำตอบที่ถูกต้องที่สุด
                    </p>

                </div>

        `;


        topic.questions.forEach(
            (question, index) => {

                html += `

                    <div class="question">

                        <h3>
                            ${index + 1}.
                            ${question.question}
                        </h3>

                        <div class="choices">
                `;


                question.choices.forEach(
                    (choice, choiceIndex) => {

                        html += `

                            <button
                                class="choice"
                                onclick="
                                    answerQuestion(
                                        ${index},
                                        ${choiceIndex},
                                        this
                                    )
                                "
                            >
                                ${choice}
                            </button>

                        `;

                    }
                );


                html += `

                        </div>

                        <div
                            id="result-${index}"
                            class="answer-result"
                        ></div>

                    </div>

                `;

            }
        );


        html += `

                <div class="score-box">

                    <h2>
                        คะแนน:
                        <span id="score">0</span>
                        /
                        ${topic.questions.length}
                    </h2>

                    <button
                        class="main-btn"
                        onclick="resetQuiz()"
                        style="
                            border:none;
                            cursor:pointer;
                            margin-top:15px;
                        "
                    >
                        เริ่มใหม่
                    </button>

                </div>

            </div>

        `;


        contentBox.innerHTML =
            html;


        window.currentQuiz =
            topic;


        score = 0;
        answered = [];

        return;
    }


    /* =================================================
       ARTICLE
    ================================================= */

    topic.sections.forEach(
        (section, index) => {

            html += `

                <section class="article-section">

                    <div class="section-number">
                        ${String(index + 1).padStart(2, "0")}
                    </div>

                    <div>

                        <h2>
                            ${section.title}
                        </h2>

                        <p>
                            ${section.text}
                        </p>

                    </div>

                </section>

            `;

        }
    );


    contentBox.innerHTML =
        html;


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


/* =====================================================
   QUIZ SYSTEM
===================================================== */

let score = 0;

let answered = [];


function answerQuestion(
    questionIndex,
    selected,
    button
) {

    const quiz =
        window.currentQuiz;


    if (!quiz) return;


    if (answered[questionIndex]) {
        return;
    }


    answered[questionIndex] =
        true;


    const question =
        quiz.questions[questionIndex];


    const result =
        document.getElementById(
            `result-${questionIndex}`
        );


    const buttons =
        button.parentElement.querySelectorAll(
            ".choice"
        );


    buttons.forEach(
        (btn) => {

            btn.disabled = true;

        }
    );


    if (
        selected === question.answer
    ) {

        score++;


        button.classList.add(
            "correct"
        );


        result.innerHTML = `
            <span class="correct-text">
                ✓ ถูกต้อง!
            </span>
        `;

    } else {

        button.classList.add(
            "wrong"
        );


        buttons[
            question.answer
        ].classList.add(
            "correct"
        );


        result.innerHTML = `
            <span class="wrong-text">
                ✕ ยังไม่ถูก
                คำตอบที่ถูกแสดงเป็นสีเขียว
            </span>
        `;

    }


    const scoreElement =
        document.getElementById(
            "score"
        );


    if (scoreElement) {

        scoreElement.textContent =
            score;

    }

}


/* =====================================================
   RESET QUIZ
===================================================== */

function resetQuiz() {

    score = 0;

    answered = [];

    showTopic("quiz");

}
